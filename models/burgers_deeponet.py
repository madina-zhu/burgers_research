import os
os.environ["DDE_BACKEND"] = "tensorflow.compat.v1"
import deepxde as dde
import numpy as np
import matplotlib.pyplot as plt


# =====================================================
# НАСТРОЙКИ
# =====================================================

# Количество различных начальных функций для обучения
# DeepONet учится на разных u0(x)
NUM_FUNCTIONS = 10

# Количество точек дискретизации по пространству (x)
# 64 точки от -1 до 1
NX = 64

# Количество точек дискретизации по времени (t)
# 200 точек от 0 до 1
NT = 200

# Коэффициент вязкости из уравнения Бюргерса
# nu = 0.01/π - стандартное значение для этого примера
nu = 0.01 / np.pi

# Фиксируем seed для воспроизводимости результатов
np.random.seed(42)


# =====================================================
# РЕШЕНИЕ УРАВНЕНИЯ БЮРГЕРСА ЧИСЛЕННЫМ МЕТОДОМ
# =====================================================

def solve_burgers(u0, nx=64, nt=200):
    """
    Решает уравнение Бюргерса методом конечных разностей.
    Используется для генерации обучающих данных для DeepONet.
    
    Параметры:
    u0 - начальное условие (массив размера nx)
    nx - количество точек по пространству
    nt - количество точек по времени
    
    Возвращает:
    x - координаты пространства
    t - координаты времени
    u - решение u(x,t) размером (nt, nx)
    """
    
    # Создаём равномерную сетку по пространству от -1 до 1
    x = np.linspace(-1, 1, nx)
    # Создаём равномерную сетку по времени от 0 до 1
    t = np.linspace(0, 1, nt)
    
    # Шаг по пространству
    dx = x[1] - x[0]
    # Шаг по времени
    dt = t[1] - t[0]
    
    # Инициализируем массив решения: нули размером (время, пространство)
    u = np.zeros((nt, nx))
    
    # Начальное условие: в момент t=0 поле равно u0
    u[0, :] = u0.flatten()
    
    # Основной цикл по времени (метод конечных разностей)
    for n in range(nt - 1):
        # Копируем текущий слой по времени для вычислений
        un = u[n, :].copy()
        
        # Цикл по внутренним точкам пространства (границы обрабатываются отдельно)
        for i in range(1, nx - 1):
            # Конвективный член: u * ∂u/∂x
            # Аппроксимируем разностью назад: u[i] * (u[i] - u[i-1]) / dx
            convection = (
                un[i]                     # текущее значение u
                * dt / dx                 # dt/dx
                * (un[i] - un[i - 1])     # разность назад
            )
            
            # Диффузионный член: ν * ∂²u/∂x²
            # Аппроксимируем центральной разностью
            diffusion = (
                nu                        # коэффициент вязкости
                * dt / dx**2              # dt / dx²
                * (un[i + 1] - 2 * un[i] + un[i - 1])  # вторая производная
            )
            
            # Обновляем значение на следующем временном слое
            # Схема: u^{n+1} = u^n - конвекция + диффузия
            u[n + 1, i] = (
                un[i]        # текущее значение
                - convection # вычитаем конвекцию
                + diffusion  # прибавляем диффузию
            )
        
        # Граничные условия Дирихле: u = 0 на левой границе (x = -1)
        u[n + 1, 0] = 0
        # Граничные условия Дирихле: u = 0 на правой границе (x = 1)
        u[n + 1, -1] = 0
        
        # Обрезаем значения до [-5, 5] для численной устойчивости
        # Предотвращает выбросы при больших градиентах
        u[n + 1] = np.clip(u[n + 1], -5, 5)
    
    # Возвращаем координаты и решение
    return x, t, u


# =====================================================
# ФОРМИРОВАНИЕ ДАННЫХ ДЛЯ ОБУЧЕНИЯ DEEPONET
# =====================================================

# Точки, в которых известны значения начального условия
# Сетка по пространству для измерения u0(x)
x_sensor = np.linspace(-1, 1, NX)[:, None]

# Списки для хранения входных и выходных данных
branch_inputs = []  # Branch net вход: значения начального условия
trunk_inputs = []   # Trunk net вход: координаты (x, t)
outputs = []        # Выход: решение u(x,t)

# Генерируем NUM_FUNCTIONS различных начальных условий
# DeepONet учится отображению u0(x) → u(x,t)
for k in range(NUM_FUNCTIONS):
    
    # Случайная амплитуда начального условия от 0.5 до 1.5
    amplitude = np.random.uniform(0.5, 1.5)
    
    # Случайная частота от 1 до 3 (разные формы начального условия)
    frequency = np.random.randint(1, 4)
    
    # Формируем начальное условие: u0(x) = -amplitude * sin(frequency * π * x)
    # Знак минус для соответствия стандартному примеру
    u0 = -amplitude * np.sin(frequency * np.pi * x_sensor)
    
    # Решаем уравнение Бюргерса численно для этого начального условия
    x_eval, t_eval, u_numeric = solve_burgers(u0, nx=NX, nt=NT)
    
    # Создаём сетку из всех точек (x, t) для trunk net
    # meshgrid создаёт все комбинации x и t
    xx, tt = np.meshgrid(x_eval, t_eval)
    
    # Объединяем x и t в массив [x, t] для каждой точки
    X = np.vstack((xx.flatten(), tt.flatten())).T
    
    # Истинное решение u(x,t) - цель для обучения
    y = u_numeric.flatten()[:, None]
    
    # Для branch net: повторяем начальное условие для каждой точки (x,t)
    # Так как branch net не зависит от координат, а только от функции u0
    branch = np.tile(u0.flatten(), (X.shape[0], 1))
    
    # Сохраняем данные
    branch_inputs.append(branch)  # branch вход: u0(x) для всех x
    trunk_inputs.append(X)        # trunk вход: координаты (x,t)
    outputs.append(y)             # выход: u(x,t)


# =====================================================
# ОБЪЕДИНЕНИЕ ДАННЫХ
# =====================================================

# Вертикально объединяем все данные для всех начальных функций
branch_inputs = np.vstack(branch_inputs).astype(np.float32)
trunk_inputs = np.vstack(trunk_inputs).astype(np.float32)
outputs = np.vstack(outputs).astype(np.float32)


# =====================================================
# РАЗДЕЛЕНИЕ НА ОБУЧАЮЩУЮ И ТЕСТОВУЮ ВЫБОРКИ (80% / 20%)
# =====================================================

# Общее количество точек
N = branch_inputs.shape[0]

# Случайное перемешивание индексов
idx = np.random.permutation(N)

# 80% точек для обучения
train_size = int(0.8 * N)

# Индексы обучения: первые 80%
train_idx = idx[:train_size]
# Индексы теста: последние 20%
test_idx = idx[train_size:]

# Формируем обучающие данные
X_train = (
    branch_inputs[train_idx],  # branch входы
    trunk_inputs[train_idx]    # trunk входы
)
y_train = outputs[train_idx]   # цели

# Формируем тестовые данные
X_test = (
    branch_inputs[test_idx],
    trunk_inputs[test_idx]
)
y_test = outputs[test_idx]


# =====================================================
# СОЗДАНИЕ ОБЪЕКТА ДАННЫХ DEEPXDE
# =====================================================

# Triple - тип данных для DeepONet: три компонента (branch, trunk, выход)
data = dde.data.Triple(
    X_train=X_train,  # входы для обучения
    y_train=y_train,  # цели для обучения
    X_test=X_test,    # входы для теста
    y_test=y_test,    # цели для теста
)


# =====================================================
# СОЗДАНИЕ НЕЙРОННОЙ СЕТИ (DeepONet)
# =====================================================

# DeepONet состоит из двух подсетей:
# 1. Branch net - принимает начальное условие u0(x) (размер NX = 64)
# 2. Trunk net - принимает координаты (x, t) (размер 2)
net = dde.maps.DeepONet(
    [NX, 64, 64],    # Branch net: вход 64 (u0), два скрытых слоя по 64 нейрона
    [2, 64, 64],     # Trunk net: вход 2 (x,t), два скрытых слоя по 64 нейрона
    activation="tanh",                      # Функция активации
    kernel_initializer="Glorot normal",     # Инициализация весов
)

# Создаём модель DeepXDE
model = dde.Model(data, net)


# =====================================================
# ПЕРВЫЙ ЭТАП ОБУЧЕНИЯ: ADAM
# =====================================================

# Компилируем модель с оптимизатором Adam и learning rate 1e-3
model.compile(
    "adam",
    lr=1e-3,
    metrics=["l2 relative error"],  # Отслеживаем относительную L2 ошибку
)

# Запускаем обучение на 3000 итераций, выводим результат каждые 500
losshistory, train_state = model.train(
    iterations=3000,
    display_every=500,
)


# =====================================================
# ВТОРОЙ ЭТАП ОБУЧЕНИЯ: L-BFGS (точная настройка)
# =====================================================

# Перекомпилируем с оптимизатором L-BFGS
# L-BFGS даёт более точную сходимость, чем Adam
model.compile("L-BFGS")

# Запускаем обучение до сходимости (без указания итераций)
losshistory, train_state = model.train()


# =====================================================
# ПРЕДСКАЗАНИЕ И ОЦЕНКА ТОЧНОСТИ
# =====================================================

# Делаем предсказание для всех входных данных
y_pred = model.predict((branch_inputs, trunk_inputs))

# Вычисляем относительную L2 ошибку
error = dde.metrics.l2_relative_error(outputs, y_pred)

# Выводим результат
print("\n===== TRUE DEEPONET =====")
print("L2 error:", error)


# =====================================================
# СОХРАНЕНИЕ ПРЕДСКАЗАНИЙ
# =====================================================

# Объединяем trunk входы (x,t), истинные значения и предсказания
results = np.hstack((
    trunk_inputs,   # столбцы: x, t
    outputs,        # столбец: u_true
    y_pred          # столбец: u_pred
))

# Сохраняем в текстовый файл
np.savetxt(
    "results/deeponet_predictions.dat",
    results,
    header="x t u_true u_pred"  # Заголовок с названиями столбцов
)


# =====================================================
# ВИЗУАЛИЗАЦИЯ: ГРАФИК ОШИБКИ ОБУЧЕНИЯ
# =====================================================

# Извлекаем суммарную функцию потерь на каждой итерации
train_loss = [sum(loss) for loss in losshistory.loss_train]

# Создаём новый график
plt.figure()

# Рисуем кривую потерь
plt.plot(train_loss)

# Логарифмическая шкала по Y (потери падают на порядки)
plt.yscale("log")

# Подписи осей
plt.xlabel("Iteration")
plt.ylabel("Loss")

# Заголовок
plt.title("DeepONet Training Loss")

# Сетка для удобства чтения
plt.grid(True)

# Автоматическое выравнивание
plt.tight_layout()

# Сохраняем график
plt.savefig("results/deeponet_loss.png", dpi=300)

# Закрываем фигуру (освобождаем память)
plt.close()


# =====================================================
# ВИЗУАЛИЗАЦИЯ: СРАВНЕНИЕ ПРЕДСКАЗАНИЙ С ИСТИНОЙ
# =====================================================

# Создаём график размером 10x5 дюймов
plt.figure(figsize=(10, 5))

# Количество точек для отображения
n_plot = 1000

# Рисуем истинные значения (синяя сплошная линия)
plt.plot(outputs[:n_plot], label="True")

# Рисуем предсказания (оранжевая пунктирная линия)
plt.plot(y_pred[:n_plot], "--", label="Prediction")

# Легенда для различения линий
plt.legend()

# Сетка
plt.grid(True)

# Выравнивание
plt.tight_layout()

# Сохраняем график
plt.savefig("results/deeponet_prediction.png", dpi=300)

