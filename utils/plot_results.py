import numpy as np
import matplotlib.pyplot as plt
import os


# =====================================================
# ПРОВЕРКА СУЩЕСТВОВАНИЯ ФАЙЛОВ РЕЗУЛЬТАТОВ
# =====================================================

# Путь к файлу с результатами FCNN (предсказания и истинные значения)
FCNN_file = "results/FCNN_predictions.dat"
# Путь к файлу с результатами DeepONet
deeponet_file = "results/deeponet_predictions.dat"

# Проверяем, существует ли файл FCNN
# Если нет - вызываем ошибку, чтобы скрипт не продолжал работу
if not os.path.exists(FCNN_file):
    raise FileNotFoundError(f"{FCNN_file} not found")

# Проверяем, существует ли файл DeepONet
if not os.path.exists(deeponet_file):
    raise FileNotFoundError(f"{deeponet_file} not found")


# =====================================================
# ЗАГРУЗКА РЕЗУЛЬТАТОВ FCNN
# =====================================================

# Загружаем данные из текстового файла FCNN
# loadtxt читает столбцы чисел из текстового файла
FCNN_data = np.loadtxt(FCNN_file)

# Структура файла: [x, t, u_true, u_pred]
# Извлекаем первый столбец (индекс 0) - координата x
x_FCNN = FCNN_data[:, 0]
# Извлекаем второй столбец (индекс 1) - координата t
t_FCNN = FCNN_data[:, 1]
# Извлекаем третий столбец (индекс 2) - истинное решение u_true
u_true_FCNN = FCNN_data[:, 2]
# Извлекаем четвёртый столбец (индекс 3) - предсказание FCNN u_pred
u_pred_FCNN = FCNN_data[:, 3]


# =====================================================
# ЗАГРУЗКА РЕЗУЛЬТАТОВ DEEPONET
# =====================================================

# Загружаем данные из текстового файла DeepONet
deeponet_data = np.loadtxt(deeponet_file)

# Извлекаем координату x
x_deep = deeponet_data[:, 0]
# Извлекаем координату t
t_deep = deeponet_data[:, 1]
# Извлекаем истинное решение
u_true_deep = deeponet_data[:, 2]
# Извлекаем предсказание DeepONet
u_pred_deep = deeponet_data[:, 3]


# =====================================================
# ПОСТРОЕНИЕ ГРАФИКОВ СРАВНЕНИЯ
# =====================================================

# Создаём фигуру размером 12x5 дюймов (ширина 12, высота 5)
plt.figure(figsize=(12, 5))

# =====================================================
# ЛЕВЫЙ ГРАФИК: РЕЗУЛЬТАТЫ FCNN
# =====================================================

# subplot(1, 2, 1) означает:
# 1 строка, 2 столбца, 1-й график (левый)
plt.subplot(1, 2, 1)

# Рисуем истинные значения (True) - синяя сплошная линия
# u_true_FCNN[:1000] - берём первые 1000 точек для наглядности
# linewidth=2 - толщина линии 2 пикселя
plt.plot(
    u_true_FCNN[:1000],
    label="True",      # подпись для легенды
    linewidth=2
)

# Рисуем предсказания FCNN - оранжевая пунктирная линия
# "--" означает пунктирный стиль линии
plt.plot(
    u_pred_FCNN[:1000],
    "--",              # пунктирная линия
    label="FCNN",      # подпись для легенды
    linewidth=2
)

# Заголовок левого графика
plt.title("FCNN Prediction")
# Подпись оси X
plt.xlabel("Point index")
# Подпись оси Y (значение решения u)
plt.ylabel("u(x,t)")
# Добавляем легенду (отображает label: True, FCNN)
plt.legend()
# Включаем сетку для удобства чтения
plt.grid(True)


# =====================================================
# ПРАВЫЙ ГРАФИК: РЕЗУЛЬТАТЫ DEEPONET
# =====================================================

# subplot(1, 2, 2) - 1 строка, 2 столбца, 2-й график (правый)
plt.subplot(1, 2, 2)

# Рисуем истинные значения (True) - синяя сплошная линия
plt.plot(
    u_true_deep[:1000],
    label="True",
    linewidth=2
)

# Рисуем предсказания DeepONet - оранжевая пунктирная линия
plt.plot(
    u_pred_deep[:1000],
    "--",
    label="DeepONet",
    linewidth=2
)

# Заголовок правого графика
plt.title("DeepONet Prediction")
# Подпись оси X
plt.xlabel("Point index")
# Подпись оси Y
plt.ylabel("u(x,t)")
# Легенда
plt.legend()
# Сетка
plt.grid(True)


# =====================================================
# СОХРАНЕНИЕ И ОТОБРАЖЕНИЕ ГРАФИКА
# =====================================================

# Автоматическое выравнивание элементов графика
# Предотвращает наложение подписей и заголовков
plt.tight_layout()

# Сохраняем график в файл
# dpi=300 - высокое разрешение (300 точек на дюйм)
plt.savefig("results/comparison_plot.png", dpi=300)

# Выводим информацию о сохранении
print("\nSaved:")
print(" - results/comparison_plot.png")

# Отображаем график на экране
# (если скрипт запущен в интерактивном режиме)
plt.show()