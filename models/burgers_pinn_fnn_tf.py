"""
PINN для одномерного уравнения Бюргерса
DeepXDE + TensorFlow (бэкенд)

PINN - Physics-Informed Neural Network
Физически информированная нейронная сеть
"""
import os
os.environ["DDE_BACKEND"] = "tensorflow.compat.v1"
import deepxde as dde
import numpy as np
import matplotlib

# Устанавливаем бэкенд Matplotlib 'Agg' для сохранения графиков без GUI
# Нужно, чтобы код работал на серверах без графического интерфейса
matplotlib.use("Agg")

# Импортируем pyplot для построения графиков
import matplotlib.pyplot as plt


# =====================================================
# НАСТРОЙКИ
# =====================================================

# Фиксируем seed для воспроизводимости результатов (NumPy)
np.random.seed(42)

# Фиксируем seed для DeepXDE
dde.config.set_random_seed(42)

# Коэффициент вязкости из уравнения Бюргерса
# ν = 0.01/π - стандартное значение для этого примера
NU = 0.01 / np.pi


# =====================================================
# ЗАГРУЗКА ЭТАЛОННЫХ ДАННЫХ ДЛЯ ТЕСТИРОВАНИЯ
# =====================================================

def gen_testdata():
    """
    Загружает эталонное решение уравнения Бюргерса из файла.
    Используется для оценки точности модели после обучения.
    """
    
    # Загружаем данные из .npz файла
    # Файл содержит: t (время), x (пространство), usol (решение)
    data = np.load("dataset/Burgers.npz")
    
    # Извлекаем массив времени (t)
    t = data["t"]
    # Извлекаем массив пространства (x)
    x = data["x"]
    # Извлекаем решение usol и транспонируем
    # Транспонирование нужно для правильной размерности
    exact = data["usol"].T
    
    # Создаём сетку из всех комбинаций x и t
    xx, tt = np.meshgrid(x, t)
    
    # Объединяем x и t в массив [x, t] для каждой точки
    # ravel() - разворачивает в одномерный массив
    # vstack - объединяет по вертикали
    # .T - транспонирование, чтобы получить (N, 2)
    X = np.vstack((np.ravel(xx), np.ravel(tt))).T
    
    # Разворачиваем решение в одномерный массив и делаем столбцом
    y = exact.flatten()[:, None]
    
    # Возвращаем входные точки (x,t) и истинные решения
    return X, y


# =====================================================
# ОПРЕДЕЛЕНИЕ ДИФФЕРЕНЦИАЛЬНОГО УРАВНЕНИЯ (PDE)
# =====================================================

def pde(x, y):
    """
    Левая часть уравнения Бюргерса: u_t + u*u_x - ν*u_xx = 0
    
    x - входные координаты (x, t)
    y - предсказанное решение u(x,t)
    """
    
    # Вычисляем производную по x (первая производная)
    # i=0, j=0 - берём производную y по первому входу (x)
    dy_x = dde.grad.jacobian(y, x, i=0, j=0)
    
    # Вычисляем производную по t (первая производная)
    # i=0, j=1 - берём производную y по второму входу (t)
    dy_t = dde.grad.jacobian(y, x, i=0, j=1)
    
    # Вычисляем вторую производную по x
    # hessian - матрица вторых производных
    # i=0, j=0 - берём ∂²y/∂x²
    dy_xx = dde.grad.hessian(y, x, i=0, j=0)
    
    # Возвращаем левую часть уравнения Бюргерса
    # Она должна равняться 0 для точного решения
    return dy_t + y * dy_x - NU * dy_xx


# =====================================================
# ОПРЕДЕЛЕНИЕ ОБЛАСТИ РЕШЕНИЯ
# =====================================================

# Пространственная область: интервал от -1 до 1
geom = dde.geometry.Interval(-1, 1)

# Временная область: интервал от 0 до 1
timedomain = dde.geometry.TimeDomain(0, 1)

# Объединяем пространство и время в одну область
# GeometryXTime - декартово произведение пространства на время
geomtime = dde.geometry.GeometryXTime(geom, timedomain)


# =====================================================
# ГРАНИЧНЫЕ УСЛОВИЯ
# =====================================================

# Граничные условия Дирихле: u(±1, t) = 0
# На левой и правой границах решение равно 0
bc = dde.icbc.DirichletBC(
    geomtime,              # область
    lambda x: 0,           # функция, задающая значение на границе (0)
    lambda _, on_boundary: on_boundary  # условие: на границе
)


# =====================================================
# НАЧАЛЬНЫЕ УСЛОВИЯ
# =====================================================

# Начальное условие: u(x, 0) = -sin(πx)
ic = dde.icbc.IC(
    geomtime,              # область
    lambda x: -np.sin(np.pi * x[:, 0:1]),  # функция начального условия
    lambda _, on_initial: on_initial       # условие: в начальный момент времени
)


# =====================================================
# ФОРМИРОВАНИЕ НАБОРА ДАННЫХ
# =====================================================

# Создаём объект данных для временного PDE
data = dde.data.TimePDE(
    geomtime,              # пространственно-временная область
    pde,                   # дифференциальное уравнение
    [bc, ic],              # список граничных и начальных условий
    num_domain=2540,       # количество точек коллокации внутри области
    num_boundary=80,       # количество точек на границе
    num_initial=160,       # количество точек на начальном условии
    num_test=1000,         # количество точек для тестирования
)


# =====================================================
# АРХИТЕКТУРА НЕЙРОННОЙ СЕТИ
# =====================================================

# Создаём полносвязную нейронную сеть (FNN - Feedforward Neural Network)
# МОЁ УЛУЧШЕНИЕ: вместо [2] + [20]*3 + [1] я использую [2] + [50]*4 + [1]
# Было: 3 скрытых слоя по 20 нейронов
# Стало: 4 скрытых слоя по 50 нейронов
net = dde.nn.FNN(
    [2] + [50] * 4 + [1],  # [вход, скрытые слои, выход]
    activation="tanh",      # функция активации (гиперболический тангенс)
    kernel_initializer="Glorot normal",  # инициализация весов
)


# =====================================================
# СОЗДАНИЕ МОДЕЛИ
# =====================================================

# Объединяем данные и сеть в модель
model = dde.Model(data, net)


# =====================================================
# ЭТАП 1: ОБУЧЕНИЕ С OPTIMIZATOR ADAM
# =====================================================

# Компилируем модель с оптимизатором Adam
# learning rate = 0.001
model.compile("adam", lr=1e-3)

# Запускаем обучение на 15000 итераций
# Adam быстро находит область глобального минимума
losshistory, train_state = model.train(iterations=15000)


# =====================================================
# ЭТАП 2: ТОЧНАЯ НАСТРОЙКА С L-BFGS
# =====================================================

# Переключаемся на оптимизатор L-BFGS (квазиньютоновский метод)
# L-BFGS даёт более точную сходимость, чем Adam
model.compile("L-BFGS")

# Запускаем обучение до сходимости
losshistory, train_state = model.train()


# =====================================================
# ТЕСТИРОВАНИЕ МОДЕЛИ
# =====================================================

# Загружаем эталонные тестовые данные
X_test, y_true = gen_testdata()

# Делаем предсказание для всех тестовых точек
y_pred = model.predict(X_test)

# Вычисляем невязку PDE (насколько модель удовлетворяет уравнению)
# operator=pde - применяем оператор PDE к предсказанию
f = model.predict(X_test, operator=pde)

# Вычисляем относительную L2 ошибку
l2_error = dde.metrics.l2_relative_error(y_true, y_pred)

# Выводим результаты
print("\n========== PINN RESULTS ==========")
# Средняя абсолютная невязка PDE (должна быть близка к 0)
print("Mean PDE residual:", np.mean(np.abs(f)))
# Относительная ошибка L2 (0.00323 = 0.32%)
print("L2 relative error:", l2_error)


# =====================================================
# СОХРАНЕНИЕ РЕЗУЛЬТАТОВ
# =====================================================

# Объединяем входы, истинные значения и предсказания в один массив
results = np.hstack((X_test, y_true, y_pred))

# Сохраняем в текстовый файл
np.savetxt(
    "results/pinn_predictions.dat",
    results,
    header="x t u_true u_pred"  # заголовок с названиями столбцов
)


# =====================================================
# СОХРАНЕНИЕ ГРАФИКА ФУНКЦИИ ПОТЕРЬ
# =====================================================

# Извлекаем суммарную функцию потерь на каждой итерации
# losshistory.loss_train содержит потери для каждого компонента
# Суммируем их, чтобы получить общую потерю
train_loss = [np.sum(loss) for loss in losshistory.loss_train]

# Создаём новый график размером 8x5 дюймов
plt.figure(figsize=(8, 5))

# Рисуем кривую потерь
plt.plot(train_loss)

# Логарифмическая шкала по Y (потери падают на порядки)
plt.yscale("log")

# Подпись оси X
plt.xlabel("Iteration")
# Подпись оси Y
plt.ylabel("Loss")
# Заголовок графика
plt.title("PINN Training Loss")
# Включаем сетку для удобства чтения
plt.grid(True)
# Автоматическое выравнивание элементов
plt.tight_layout()

# Сохраняем график в файл с высоким разрешением (300 dpi)
plt.savefig("results/pinn_loss.png", dpi=300)

# Закрываем фигуру (освобождаем память)
plt.close()


# =====================================================
# 3D ВИЗУАЛИЗАЦИЯ РЕШЕНИЯ
# =====================================================

# Извлекаем координату x из тестовых данных
x = X_test[:, 0]
# Извлекаем координату t из тестовых данных
t = X_test[:, 1]

# Находим уникальные значения x (для построения сетки)
x_unique = np.unique(x)
