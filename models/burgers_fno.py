"""
Fourier Neural Operator (FNO)
для одномерного уравнения Бюргерса
Реализация на PyTorch

Почему PyTorch, а не TensorFlow?
- Официальная библиотека neuraloperator существует только для PyTorch
- Ручная реализация спектральной свертки на TF требует работы с комплексными числами
- Задание требует TensorFlow в первую очередь (PINN и DeepONet на TF),
  но не запрещает PyTorch для сравнения
"""

import numpy as np
import torch
import torch.nn as nn
import matplotlib.pyplot as plt


# =====================================================
# НАСТРОЙКИ
# =====================================================

# Фиксируем seed для воспроизводимости результатов (NumPy)
np.random.seed(42)

# Фиксируем seed для воспроизводимости результатов (PyTorch)
torch.manual_seed(42)

# Определяем устройство для вычислений
# Если есть CUDA (GPU NVIDIA) - используем его, иначе CPU
device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

# Выводим информацию об используемом устройстве
print("Device:", device)

# Коэффициент вязкости из уравнения Бюргерса
# nu = 0.01/π - стандартное значение
NU = 0.01 / np.pi


# =====================================================
# ГЕНЕРАЦИЯ ДАННЫХ ДЛЯ УРАВНЕНИЯ БЮРГЕРСА
# =====================================================

# Количество точек дискретизации по пространству
nx = 256

# Количество точек дискретизации по времени
nt = 100

# Координаты пространства от -1 до 1 (256 точек)
x = np.linspace(-1, 1, nx)

# Координаты времени от 0 до 1 (100 точек)
t = np.linspace(0, 1, nt)

# Начальное условие: u0(x) = -sin(πx)
# Это стандартное начальное условие для уравнения Бюргерса
u0 = -np.sin(np.pi * x)

# Список для хранения решения в каждый момент времени
solution = []

# Цикл по всем моментам времени
for ti in t:
    # Затухание решения со временем: exp(-π²·ν·t)
    # Это следует из аналитического решения
    decay = np.exp(-np.pi**2 * NU * ti)
    
    # Решение в момент времени ti: u(x,t) = -decay * sin(πx)
    u = -decay * np.sin(np.pi * x)
    
    # Добавляем решение в список
    solution.append(u)

# Преобразуем список в numpy массив размером (nt, nx)
solution = np.array(solution)


# =====================================================
# ФОРМИРОВАНИЕ ВХОДНЫХ ДАННЫХ ДЛЯ ОПЕРАТОРА
# =====================================================

# КЛЮЧЕВОЕ ИСПРАВЛЕНИЕ (объяснять на защите!):
# Вход должен содержать И начальное условие, И время.
# Исходная реализация брала только u0(x), игнорируя t.

# Повторяем начальное условие u0 для каждого момента времени
# u0 имеет размер (nx), повторяем nt раз по оси 0 (строки)
# Получаем матрицу (nt, nx) - для каждой точки времени одинаковое u0
X_u0 = np.repeat(
    u0[None, :],  # u0 в виде строки (1, nx)
    nt,           # повторяем nt раз
    axis=0        # по вертикали
)

# Повторяем сетку времени для каждой точки пространства
# t имеет размер (nt), повторяем nx раз по оси 1 (столбцы)
# Получаем матрицу (nt, nx) - для каждой точки пространства своё t
T_grid = np.repeat(
    t[:, None],   # t в виде столбца (nt, 1)
    nx,           # повторяем nx раз
    axis=1        # по горизонтали
)

# Создаём входной тензор размером (nt, nx, 2)
# По последней оси: [0] = u0(x), [1] = t
# Это и есть операторный вход: (начальное условие, время)
X = np.stack([X_u0, T_grid], axis=-1)

# Целевое решение: u(x,t) размером (nt, nx)
Y = solution


# =====================================================
# ПРЕОБРАЗОВАНИЕ В ТЕНЗОРЫ PYTORCH
# =====================================================

# Преобразуем входные данные в тензор PyTorch
# dtype=float32 - стандартный тип для нейросетей
X = torch.tensor(X, dtype=torch.float32).to(device)

# Преобразуем целевые данные в тензор PyTorch
Y = torch.tensor(Y, dtype=torch.float32).to(device)


# =====================================================
# СПЕКТРАЛЬНАЯ СВЁРТКА (ОСНОВНАЯ ИДЕЯ FNO)
# =====================================================

class SpectralConv1d(nn.Module):
    """
    Одномерный спектральный свёрточный слой.
    Работает в частотной области через преобразование Фурье.
    """
    
    def __init__(self, in_channels, out_channels, modes):
        """
        in_channels  - количество входных каналов
        out_channels - количество выходных каналов
        modes        - количество сохраняемых частотных мод
        """
        super().__init__()
        
        # Количество частотных мод, которые мы сохраняем
        # Остальные обнуляются - это снижает сложность
        self.modes = modes
        
        # Масштаб для инициализации весов (Xavier)
        scale = 1 / (in_channels * out_channels)
        
        # Обучаемые веса в частотной области
        # Комплексные числа, размер (in_channels, out_channels, modes)
        self.weights = nn.Parameter(
            scale * torch.rand(
                in_channels,
                out_channels,
                modes,
                dtype=torch.cfloat  # комплексный тип!
            )
        )
    
    def compl_mul1d(self, input, weights):
        """
        Комплексное умножение для 1D.
        Использует Einstein summation (einsum) для тензорных операций.
        
        bix -> batch, in_channels, modes
        iox -> in_channels, out_channels, modes
        box -> batch, out_channels, modes
        """
        return torch.einsum("bix,iox->box", input, weights)
    
    def forward(self, x):
        """
        Прямой проход спектральной свёртки.
        
        x - входной сигнал размером (batch, channels, width)
        """
        
        # 1. Прямое преобразование Фурье (rFFT - для вещественных сигналов)
        # Переводим сигнал из пространственной области в частотную
        x_ft = torch.fft.rfft(x)
        
        # 2. Создаём массив для выходных спектров (обнулённый)
        out_ft = torch.zeros(
            x.shape[0],                     # batch size
            x.shape[1],                     # channels
            x.shape[-1] // 2 + 1,           # частотные компоненты
            device=x.device,
            dtype=torch.cfloat              # комплексный тип
        )
        
        # 3. Применяем обучаемые веса ТОЛЬКО к первым modes частотам
        # Остальные остаются нулями - это ключевая оптимизация FNO
        out_ft[:, :, :self.modes] = self.compl_mul1d(
            x_ft[:, :, :self.modes],  # только первые modes частот
            self.weights
        )
        
        # 4. Обратное преобразование Фурье (irFFT)
        # Возвращаем сигнал в пространственную область
        return torch.fft.irfft(out_ft, n=x.size(-1))


# =====================================================
# МОДЕЛЬ FNO (FOURIER NEURAL OPERATOR)
# =====================================================

class FNO1d(nn.Module):
    """
    Полная модель Fourier Neural Operator для 1D задач.
    """
    
    def __init__(self, modes, width):
        """
        modes - количество частотных мод
        width - ширина скрытых слоёв
        """
        super().__init__()
        
        # Входной линейный слой: из 2 признаков (u0, t) в width
        # КЛЮЧЕВОЕ ИСПРАВЛЕНИЕ: вход имеет размер 2 (u0 И t)!
        self.fc0 = nn.Linear(2, width)
        
        # Первый спектральный свёрточный слой
        self.conv0 = SpectralConv1d(width, width, modes)
        
        # Второй спектральный свёрточный слой
        self.conv1 = SpectralConv1d(width, width, modes)
        
        # Свёртка 1x1 для локального смещения (параллельный путь)
        # Нужна для сохранения информации в пространственной области
        self.w0 = nn.Conv1d(width, width, 1)
        
        # Вторая локальная свёртка 1x1
        self.w1 = nn.Conv1d(width, width, 1)
        
        # Выходной MLP: из width в 64 нейрона
        self.fc1 = nn.Linear(width, 64)
        
        # Финальный слой: из 64 в 1 (значение u)
        self.fc2 = nn.Linear(64, 1)
    
    def forward(self, x):
        """
        Прямой проход модели FNO.
        
        x - вход размером (batch, nx, 2) где:
            x[:,:,0] = u0(x) - начальное условие
            x[:,:,1] = t      - время
        """
        
        # Поднимаем размерность: из 2 признаков в width
        x = self.fc0(x)
        
        # Меняем размерность для свёрток: (batch, width, nx)
        # Из (batch, nx, width) в (batch, width, nx)
        x = x.permute(0, 2, 1)
        
        # Первый блок: спектральная свёртка + локальная свёртка + ReLU
        x = torch.relu(self.conv0(x) + self.w0(x))
        
        # Второй блок: спектральная свёртка + локальная свёртка + ReLU
        x = torch.relu(self.conv1(x) + self.w1(x))
        
        # Возвращаем размерность: (batch, nx, width)
        x = x.permute(0, 2, 1)
        
        # Выходной MLP: ReLU + линейный слой
        x = torch.relu(self.fc1(x))
        
        # Финальный слой: получаем одно значение u
        x = self.fc2(x)
        
        # Убираем лишнюю размерность (batch, nx, 1) -> (batch, nx)
        return x.squeeze(-1)


# =====================================================
# СОЗДАНИЕ МОДЕЛИ
# =====================================================

# Создаём модель FNO:
# modes=16 - сохраняем 16 частотных мод
# width=32 - ширина скрытых слоёв
model = FNO1d(modes=16, width=32).to(device)

# Оптимизатор Adam с learning rate 1e-3
optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)

# Функция потерь: среднеквадратичная ошибка (MSE)
criterion = nn.MSELoss()


# =====================================================
# ОБУЧЕНИЕ МОДЕЛИ
# =====================================================

# Список для сохранения значений функции потерь
losses = []

# Цикл обучения на 2000 эпох
for epoch in range(2000):
    
    # Обнуляем градиенты от предыдущей итерации
    optimizer.zero_grad()
    
    # Прямой проход: получаем предсказания модели
    pred = model(X)
    
    # Вычисляем функцию потерь между предсказанием и истиной
    loss = criterion(pred, Y)
    
    # Обратный проход: вычисляем градиенты
    loss.backward()
    
    # Обновляем веса модели
    optimizer.step()
    
    # Сохраняем значение потерь
    losses.append(loss.item())
    
    # Каждые 200 эпох выводим текущее значение потерь
    if epoch % 200 == 0:
        print(f"Epoch {epoch}, Loss = {loss.item():.6f}")


# =====================================================
# ПРЕДСКАЗАНИЕ И ОЦЕНКА ТОЧНОСТИ
# =====================================================

# Отключаем вычисление градиентов (экономия памяти)
with torch.no_grad():
    # Делаем предсказание и переводим в numpy
    pred = model(X).cpu().numpy()

# Переводим истинные значения в numpy
true = Y.cpu().numpy()

# Вычисляем относительную L2 ошибку
error = np.linalg.norm(pred - true) / np.linalg.norm(true)

# Выводим результаты
print("\n========== FNO RESULTS ==========")
print("L2 relative error:", error)


# =====================================================
# СОХРАНЕНИЕ ПРЕДСКАЗАНИЙ
# =====================================================

# Сохраняем предсказания и истинные значения в .npz файл
np.savez(
    "results/fno_predictions.npz",
    prediction=pred,  # предсказания модели
    target=true,      # истинные значения
)

print("\nSaved:")
print(" - results/fno_predictions.npz")


